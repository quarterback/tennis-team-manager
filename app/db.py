# (attribute name on the engine driver -> players column) for the 9 skills.
_SKILL_COLS = (
    "serve_power", "serve_placement", "return_game", "forehand", "backhand",
    "movement", "stamina", "mental", "consistency",
)


def save_prospect(conn: sqlite3.Connection, pr, *, school: str = "",
                  division: str = "") -> int:
    """Upsert one app.development.Prospect (keyed on its stable `pid`),
    persisting attributes AND the full origin/scholarship payload. Returns the
    row id."""
    drivers = pr.engine_player()
    skills = {c: float(getattr(drivers, c, 0.0) or 0.0) for c in _SKILL_COLS}
    cols = (
        "pid", "name", "country", "gender", *_SKILL_COLS,
        "rating", "reliability", "school", "division", "class_year",
        "hometown", "high_school", "birthday", "major", "secondary_country",
        "region", "academic_rating", "recruit_stars", "scholarship", "walk_on",
    )
    vals = (
        pr.pid, pr.name, pr.country, pr.gender,
        *(skills[c] for c in _SKILL_COLS),
        float(getattr(pr, "rating", 0.0) or pr.str_value()),
        float(getattr(pr, "reliability", 0.0) or 0.0),
        school or "", division or "", getattr(pr, "class_year", ""),
        getattr(pr, "hometown", ""), getattr(pr, "high_school", ""),
        getattr(pr, "birthday", ""), getattr(pr, "major", ""),
        getattr(pr, "secondary_country", ""), getattr(pr, "region", ""),
        int(getattr(pr, "academic_rating", 0) or 0),
        int(getattr(pr, "recruit_stars", 0) or 0),
        float(getattr(pr, "scholarship", 0.0) or 0.0),
        1 if getattr(pr, "walk_on", False) else 0,
    )
    placeholders = ",".join("?" * len(cols))
    updates = ",".join(f"{c}=excluded.{c}" for c in cols if c != "pid")
    cur = conn.execute(
        f"INSERT INTO players ({','.join(cols)}) VALUES ({placeholders}) "
        f"ON CONFLICT(pid) DO UPDATE SET {updates}",
        vals,
    )
    return cur.lastrowid


def load_player_row(conn: sqlite3.Connection, pid: str) -> dict | None:
    """Read a persisted player back as a plain dict (origins included)."""
    row = conn.execute("SELECT * FROM players WHERE pid = ?", (pid,)).fetchone()
    return dict(row) if row else None


@contextmanager
def transaction(path: str | None = None):
    conn = connect(path)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def save_match(conn: sqlite3.Connection, result: MatchResult, *, seed: int,
               fmt_json: str = "", p0_id: int | None = None,
               p1_id: int | None = None) -> int:
    cur = conn.execute(
        "INSERT INTO matches (seed, fidelity, fmt, p0_id, p1_id, winner, "
        "scoreline, games_p0, games_p1) VALUES (?,?,?,?,?,?,?,?,?)",
        (seed, result.fidelity, fmt_json, p0_id, p1_id, result.winner,
         result.scoreline, result.games_won[0], result.games_won[1]),
    )
    match_id = cur.lastrowid
    if result.fidelity != "fast":
        for side, s in enumerate(result.stats):
            conn.execute(
                "INSERT INTO match_stats (match_id, side, aces, double_faults, "
                "first_serve_pct, serve_points_won_pct, break_points_faced, "
                "break_points_saved, break_points_converted, winners, "
                "unforced_errors, points_won) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                (match_id, side, s.aces, s.double_faults, s.first_serve_pct,
                 s.serve_points_won_pct, s.break_points_faced, s.break_points_saved,
                 s.break_points_converted, s.winners, s.unforced_errors, s.points_won),
            )
    return match_id
